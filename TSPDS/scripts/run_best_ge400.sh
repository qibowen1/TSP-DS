#!/usr/bin/env bash
set -euo pipefail

# Run the best-parameter TSPDS memetic search on the >=400 CSV instances.
# Usage:
#   ./scripts/run_best_ge400.sh [cutoff_seconds] [repeats] [workers]
# Example:
#   ./scripts/run_best_ge400.sh 2400 3 24

CUTOFF="${1:-2400}"
REPEATS="${2:-3}"
WORKERS="${3:-24}"
GE400_INST="rd400_0_80.csv,rd400_l_80.csv,att532_0_80.csv,att532_l_80.csv,ali535_0_80.csv,ali535_l_80.csv,d657_0_80.csv,d657_l_80.csv,rat783_0_80.csv,rat783_l_80.csv,u1060_0_80.csv,u1060_l_80.csv,pcb1173_0_80.csv,pcb1173_l_80.csv"

TSPDS_VERBOSE=0 \
TSPDS_INITIAL_TARGET_SEED=0 \
TSPDS_TARGET_VND=0 \
TSPDS_INITIAL_BACKBONE_SEED=1 \
TSPDS_ROUTE_OROPT=0 \
TSPDS_COMPOUND_LKH=0 \
TSPDS_ROUTE_PERTURBATION=0 \
TSPDS_FINAL_FULL_LKH=0 \
TSPDS_DRONES=1,3,5 \
TSPDS_REPEATS="$REPEATS" \
TSPDS_WORKERS="$WORKERS" \
TSPDS_POPULATION_SIZE=3 \
TSPDS_MUTATION_PROBABILITY=0.6 \
TSPDS_MUTATION_K=3 \
TSPDS_CROSSOVER=1 \
TSPDS_LS_TWO_OPT=1 \
TSPDS_LS_CROSS_STATION=1 \
TSPDS_LS_DRONE_BALANCE=1 \
TSPDS_LS_TRUCK_BOTTLENECK=1 \
TSPDS_LS_DRONE_BOTTLENECK=1 \
TSPDS_LS_TRUCK_DRONE_SWAP=1 \
TSPDS_LS_FARTHEST_TRUCK_TO_DRONE=1 \
TSPDS_COMPOUND_EXCHANGE=1 \
TSPDS_INSTANCE="$GE400_INST" \
TSPDS_MAX_RUN_TIME="$CUTOFF" \
./build/bin/TSPDS.out
